# Rate My Human: The One-Line Review
#
# This program writes one fixed review to standard output.
# It takes no input, reads no files, and uses no randomness,
# so every run produces exactly the same single line.
#
# The review lives in the print statement below and nowhere else.
# Nothing is printed before it and nothing after it.
# The process ends normally right after the line appears.
# A review is funniest when the praise and the complaint
# sit in the same sentence, one star apart.
# Run it with: python3 main.py
# One fixed review line on stdout.
print("Five stars for enthusiasm, one star for reading the instructions.")
